import test from 'node:test'
import assert from 'node:assert/strict'
import {createHash} from 'node:crypto'
import {existsSync,mkdirSync,mkdtempSync,readFileSync,writeFileSync} from 'node:fs'
import path from 'node:path'
import {pathToFileURL} from 'node:url'
import ts from 'typescript'
import {PDFDocument} from 'pdf-lib'

const executable=process.env.PUPPETEER_EXECUTABLE_PATH
assert.ok(executable&&existsSync(executable),'Supply an installed managed Chromium executable; this acceptance must render without mocks')
const directory=path.resolve('test-results/native-pdf-output')
mkdirSync(directory,{recursive:true})
const compiledDirectory=mkdtempSync(path.join(directory,'compiled-'))
const source=readFileSync('src/lib/pdf/generatePdf.ts','utf8')
const compiled=path.join(compiledDirectory,'generatePdf.mjs')
writeFileSync(compiled,ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ES2022,target:ts.ScriptTarget.ES2022}}).outputText)
const {generatePdf}=await import(pathToFileURL(compiled))
const evidence={node:process.version,sourceSha256:createHash('sha256').update(source).digest('hex'),scope:'Native synthetic PDF renderer and independent PDF parser; no physical-print or field acceptance',checks:[]}
const record=check=>{evidence.checks.push(check);writeFileSync(path.join(directory,'result.json'),JSON.stringify(evidence,null,2)+'\n')}
const section={section:'introduction',sectionNumber:1,title:'Synthetic only',content:'<h1>SYNTHETIC UNVERIFIED DRAFT</h1><p>No field accuracy or approval is established.</p>',autoGenerated:false,completeness:100}

for(const [paperSize,orientation,widthMm,heightMm]of [
 ['A4','portrait',210,297],['A4','landscape',297,210],
 ['A3','portrait',297,420],['A3','landscape',420,297],
]){
 test(`actual ${paperSize} ${orientation} PDF pages retain the requested geometry`,{timeout:60000},async()=>{
  const bytes=await generatePdf({title:'Synthetic native PDF acceptance',sections:[section],paperSize,orientation})
  const doc=await PDFDocument.load(bytes)
  assert.ok(doc.getPageCount()>=1)
  const sizes=doc.getPages().map(page=>page.getSize())
  for(const size of sizes){
   assert.ok(Math.abs(size.width-widthMm*72/25.4)<1,`Expected ${widthMm} mm width, actual ${size.width} PDF points`)
   assert.ok(Math.abs(size.height-heightMm*72/25.4)<1,`Expected ${heightMm} mm height, actual ${size.height} PDF points`)
  }
  const filename=`synthetic-${paperSize}-${orientation}.pdf`
  writeFileSync(path.join(directory,filename),bytes)
  record({name:`${paperSize} ${orientation}`,passed:true,pages:sizes,file:filename,sha256:createHash('sha256').update(bytes).digest('hex')})
 })
}

test('the actual renderer refuses HTML which tries to load an external resource',{timeout:60000},async()=>{
 await assert.rejects(()=>generatePdf({title:'Synthetic blocked resource',sections:[{...section,content:'<img src="https://example.invalid/synthetic-resource" />'}]}),/external resources/)
 record({name:'External resource refused',passed:true})
})
