/** @jest-environment node */
import { PDFDocument } from 'pdf-lib'
import { generatePdf } from '@/lib/pdf/generatePdf'
import type { SectionContent } from '@/types/surveyReport'

const section = (content: string): SectionContent => ({
  section: 'INTRODUCTION', sectionNumber: 3, title: 'Saved observations', content,
  autoGenerated: false, completeness: 100,
})

test('renders the saved table on A3 landscape without executing or including scripts', async () => {
  const pdf = await generatePdf({ title: 'Draft', paperSize: 'A3', orientation: 'landscape', sections: [
    section('<script>fetch("http://127.0.0.1/private")</script><p>Saved remarks</p><table><tr><th>Station</th><th>Easting</th></tr><tr><td>BM1</td><td>500000.125</td></tr></table>'),
  ] })
  const page = (await PDFDocument.load(pdf)).getPage(0)
  expect(page.getWidth()).toBeCloseTo(1190.55, 1)
  expect(page.getHeight()).toBeCloseTo(841.89, 1)
  const body = pdf.toString('latin1')
  expect(body).toContain('(Saved remarks)')
  expect(body).toContain('(500000.125)')
  expect(body).not.toContain('http://127.0.0.1/private')
})

test.each(['http://127.0.0.1/private', 'data:image/png;base64,AAA'])(
  'refuses to omit a figure from a PDF',
  async (source) => {
    await expect(generatePdf({ title: 'Draft', sections: [section('<img src="' + source + '">')] }))
      .rejects.toThrow('contains figures or attachments')
  },
)
