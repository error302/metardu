export function exportLandXMLSurface(
  _points: CivilPoint[], _projectName: string, _utmZone: number,
  _hemisphere: 'N' | 'S', _datum: string,
): string {
  throw new Error('LandXML surface export requires a retained surface revision with its original mesh and reference. Select a saved revision in the civil handoff workspace.')
}
export type CivilFormat = 'civil3d' | '12d' | 'moss' | 'pointcloud' | 'shapefile_csv' | 'landxml_surface'

export const CIVIL_FORMATS: { id: CivilFormat; label: string; software: string; ext: string; desc: string }[] = [
  { id: 'civil3d',        label: 'Civil 3D PENZD',      software: 'AutoCAD Civil 3D',            ext: 'csv',  desc: 'Direct import into Civil 3D via Points → Import Points → PENZD' },
  { id: '12d',            label: '12d Model CSV',        software: '12d Model',                   ext: 'csv',  desc: 'Import as 12d survey string data' },
  { id: 'moss',           label: 'MOSS / Microdrainage', software: 'MOSS, Microdrainage',         ext: 'def',  desc: 'ASCII point format for MOSS and drainage software' },
  { id: 'pointcloud',     label: 'ASCII Point Cloud',    software: 'CloudCompare, ReCap, Civil 3D',ext: 'txt', desc: 'X Y Z intensity — opens in CloudCompare and Autodesk ReCap' },
  { id: 'shapefile_csv',  label: 'Shapefile CSV',        software: 'QGIS, ArcGIS, MapInfo',       ext: 'csv',  desc: 'CSV with WGS84 lat/lon — import as shapefile in QGIS or ArcGIS' },
  { id: 'landxml_surface',label: 'Retained TIN LandXML', software: 'Civil 3D, InfraWorks, 12d', ext: 'xml', desc: 'Exact saved surface revision with original vertices, faces and reference' },
]

export function exportCivil(
  points: CivilPoint[],
  format: CivilFormat,
  projectName: string,
  utmZone: number,
  hemisphere: 'N' | 'S',
  datum: string
): { content: string; ext: string } {
  const reference=reportCrs({utmZone,hemisphere,datum})
  if(!reference.verified)throw new Error('Civil handoff requires a declared, supported project CRS.')
  validateCivilPoints(points)
  for(const point of points){const range=validateCoordinateRange(point.easting,point.northing,reference.epsgCode);if(!range.valid)throw new Error(range.errors.join('; '))}
  const fmt = CIVIL_FORMATS.find((f: (typeof CIVIL_FORMATS)[number]) => f.id === format)
  if(!fmt)throw new Error('Unknown civil export format; no substitute format was generated.')
  if(!projectName.trim()||/[\r\n\u0000]/.test(projectName))throw new Error('Civil export project name is missing or contains record separators.')
  switch (format) {
    case 'civil3d':         return { content: exportCivil3DCSV(points, projectName),             ext: fmt.ext }
    case '12d':             return { content: export12dCSV(points, projectName),                  ext: fmt.ext }
    case 'moss':            return { content: exportMossDEF(points),                              ext: fmt.ext }
    case 'pointcloud':      return { content: exportASCIIPointCloud(points),                      ext: fmt.ext }
    case 'shapefile_csv':   return { content: exportShapefileCSV(points, utmZone, hemisphere, datum), ext: fmt.ext }
    case 'landxml_surface': return { content: exportLandXMLSurface(points, projectName, utmZone, hemisphere, datum), ext: fmt.ext }
    default:                return { content: exportCivil3DCSV(points, projectName),             ext: 'csv' }
  }
}
