/**
 * Civil Engineering Data Handoff
 * Packages survey data for direct use in AutoCAD Civil 3D, 12d, QGIS, ArcGIS.
 * No extra computation — formats data from the existing project.
 */

import { utmToWgs84 } from '@/lib/spatial/projectReferenceSystem'
import { reportCrs } from '@/lib/generators/reportCrs'
import {validateCoordinateRange} from '@/lib/spatial/projectCrs'

export interface CivilPoint {
  name: string
  easting: number|null
  northing: number|null
  elevation: number|null
  is_control: boolean
  code?: string
}

export interface AlignmentPoint {
  chainage: number
  easting: number
  northing: number
  elevation: number
}

type CompleteCivilPoint=CivilPoint&{easting:number;northing:number;elevation:number}
function validateCivilPoints(points:CivilPoint[]):asserts points is CompleteCivilPoint[]{
  if(!points.length)throw new Error('Select at least one survey point to export.')
  const names=new Set<string>()
  for(const point of points){
    if(typeof point.name!=='string'||!point.name.trim()||names.has(point.name)||/[\r\n\u0000]/.test(point.name)||point.code&&/[\r\n\u0000]/.test(point.code))throw new Error('Civil point names must be nonblank and unique; names and codes must contain no record separators.')
    names.add(point.name)
    if([point.easting,point.northing,point.elevation].some(value=>typeof value!=='number'||!Number.isFinite(value)))throw new Error('A civil point has missing or nonfinite coordinates or height. Retain it and complete the source evidence; no zero was invented.')
  }
}
const csv=(value:string)=>/[",\r\n]/.test(value)?`"${value.replace(/"/g,'""')}"`:value

// ── CSV for Civil 3D point import (PENZD format) ─────────────────────────────
// Civil 3D reads: Point#,Easting,Northing,Elevation,Description
export function exportCivil3DCSV(points: CivilPoint[], projectName: string): string {
  validateCivilPoints(points)
  const lines = [
    `# Civil 3D Point Import — ${projectName}`,
    `# Generated by METARDU | Format: PENZD`,
    `# Point No.,Easting(m),Northing(m),Elevation(m),Description`,
  ]
  points.forEach((p, i) => {
    const desc = p.is_control ? `CTRL-${p.name}` : p.code || `SURV-${p.name}`
    lines.push(`${i + 1},${p.easting.toFixed(4)},${p.northing.toFixed(4)},${p.elevation.toFixed(4)},${csv(desc)}`)
  })
  return lines.join('\n')
}

// ── 12d Model CSV format ──────────────────────────────────────────────────────
// 12d reads: Name,Easting,Northing,RL,String
export function export12dCSV(points: CivilPoint[], projectName: string): string {
  validateCivilPoints(points)
  const lines = [
    `! 12d Model Survey Data — ${projectName}`,
    `! Generated by METARDU`,
    `! Name,Easting,Northing,RL,String`,
  ]
  points.forEach((p) => {
    const str = p.is_control ? 'CTRL' : 'SURV'
    lines.push(`${csv(p.name)},${p.easting.toFixed(4)},${p.northing.toFixed(4)},${p.elevation.toFixed(4)},${str}`)
  })
  return lines.join('\n')
}

// ── MOSS / Microdrainage DEF format ──────────────────────────────────────────
export function exportMossDEF(points: CivilPoint[]): string {
  validateCivilPoints(points)
  const lines = ['MOSS Survey Points', 'BEGIN DATA']
  points.forEach((p) => {
    lines.push(`${p.easting.toFixed(3)} ${p.northing.toFixed(3)} ${p.elevation.toFixed(3)} ${p.name}`)
  })
  lines.push('END DATA')
  return lines.join('\n')
}

// ── LAS-style ASCII point cloud (for topo surveys) ───────────────────────────
// Can be opened in CloudCompare, Recap, Civil 3D
export function exportASCIIPointCloud(points: CivilPoint[]): string {
  validateCivilPoints(points)
  const lines = ['//X Y Z Intensity Name']
  points.forEach((p) => {
    const intensity = p.is_control ? 65535 : 32767
    lines.push(`${p.easting.toFixed(4)} ${p.northing.toFixed(4)} ${p.elevation.toFixed(4)} ${intensity} ${p.name}`)
  })
  return lines.join('\n')
}

// ── Shapefile-ready CSV (ESRI-compatible) ────────────────────────────────────
export function exportShapefileCSV(points: CivilPoint[], utmZone: number, hemisphere: 'N'|'S', datum: string): string {
  validateCivilPoints(points)
  const lines = ['Name,Easting,Northing,Elevation,Lat_WGS84,Lon_WGS84,Type,UTM_Zone']
  points.forEach((p) => {
    const { lat, lon } = utmToWgs84(p.easting, p.northing, utmZone, hemisphere, datum)
    lines.push([
      csv(p.name),
      p.easting.toFixed(4),
      p.northing.toFixed(4),
      p.elevation.toFixed(4),
      lat.toFixed(8),
      lon.toFixed(8),
      p.is_control ? 'Control' : 'Survey',
      `${utmZone}${hemisphere}`,
    ].join(','))
  })
  return lines.join('\n')
}

