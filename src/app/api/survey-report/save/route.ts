import { NextResponse } from 'next/server'
import { z } from 'zod'
import { apiHandler } from '@/lib/apiHandler'
import { db } from '@/lib/db'
import { requireProjectOwnership } from '@/lib/auth/ownership'
import { rimReportType } from '@/lib/rim/register'

export const dynamic = 'force-dynamic'
const options = { auth: true, rateLimit: { max: 60, windowMs: 60_000 } } as const
const id = z.string().uuid()
const noStore = { 'Cache-Control': 'private, no-store' }
const bodySchema = z.object({
  projectId: id, reportId: id.optional(),
  input: z.object({ reportTitle: z.string().max(250).optional(), reportNumber: z.string().max(100).optional(), revisionNumber: z.string().max(60).optional() }).passthrough(),
  sections: z.array(z.object({ section: z.string(), sectionNumber: z.number().int(), title: z.string(), content: z.string().max(500_000),
    autoGenerated: z.boolean(), completeness: z.number().min(0).max(100), manuallyEdited: z.boolean().optional() })).min(1).max(15),
  completeness: z.number().min(0).max(100).default(0),
})

export const GET = apiHandler(options, async (req, ctx) => {
  const project = id.safeParse(req.nextUrl.searchParams.get('projectId'))
  const report = id.optional().safeParse(req.nextUrl.searchParams.get('reportId') ?? undefined)
  if (!project.success || !report.success) return NextResponse.json({ error: 'Select a valid project and report.' }, { status: 400, headers: noStore })
  const access = await requireProjectOwnership(project.data, ctx.userId)
  if (!access.ok) return access.error ?? NextResponse.json({ error: 'Project unavailable.' }, { status: 404 })
  if (report.data) {
    const { rows } = await db.query<{ id: string; input_data: unknown; sections: unknown; completeness: number }>(
      'SELECT id,input_data,sections,completeness FROM survey_reports WHERE id=$1 AND project_id=$2 AND user_id=$3 AND report_type IS DISTINCT FROM $4',
      [report.data, project.data, ctx.userId, rimReportType])
    if (!rows[0]) return NextResponse.json({ error: 'Saved survey report not found in this project.' }, { status: 404, headers: noStore })
    return NextResponse.json({ report: rows[0] }, { headers: noStore })
  }
  const { rows } = await db.query<{ id: string; report_title: string | null; report_number: string | null }>(
    'SELECT id,report_title,report_number FROM survey_reports WHERE project_id=$1 AND user_id=$2 AND report_type IS DISTINCT FROM $3 AND jsonb_array_length(sections)>0 ORDER BY updated_at DESC LIMIT 100',
    [project.data, ctx.userId, rimReportType])
  return NextResponse.json({ reports: rows }, { headers: noStore })
})

export const POST = apiHandler(options, async (_req, ctx) => {
  const parsed = bodySchema.safeParse(ctx.body)
  if (!parsed.success) return NextResponse.json({ error: parsed.error.issues[0]?.message || 'Invalid survey report.' }, { status: 400, headers: noStore })
  const { projectId, reportId, input, sections, completeness } = parsed.data
  const access = await requireProjectOwnership(projectId, ctx.userId)
  if (!access.ok) return access.error ?? NextResponse.json({ error: 'Project unavailable.' }, { status: 404 })
  const values = [projectId, ctx.userId, input.reportNumber || 'SR-' + Date.now(), input.reportTitle || 'Survey Report',
    input.revisionNumber || 'Rev 0', JSON.stringify({ ...input, projectId }), JSON.stringify(sections), Math.round(completeness)]
  const { rows } = reportId
    ? await db.query<{ id: string }>(
      'UPDATE survey_reports SET report_number=$3,report_title=$4,revision=$5,input_data=$6::jsonb,sections=$7::jsonb,completeness=$8 WHERE project_id=$1 AND user_id=$2 AND id=$9 AND report_type IS DISTINCT FROM $10 RETURNING id',
      [...values, reportId, rimReportType])
    : await db.query<{ id: string }>(
      "INSERT INTO survey_reports (project_id,user_id,report_number,report_title,revision,input_data,sections,completeness,report_type,status) VALUES ($1,$2,$3,$4,$5,$6::jsonb,$7::jsonb,$8,'survey-report','draft') RETURNING id", values)
  if (!rows[0]) return NextResponse.json({ error: 'Saved survey report not found in this project.' }, { status: 404, headers: noStore })
  return NextResponse.json({ id: rows[0].id, saved: true }, { headers: noStore })
})
