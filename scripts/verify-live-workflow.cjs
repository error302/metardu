const { config } = require('dotenv');
const { Pool } = require('pg');
const { randomUUID, randomBytes } = require('crypto');
const bcrypt = require('bcryptjs');
const { chromium } = require('playwright');
const fs = require('fs');
config({path:'.env',quiet:true});
const pool = new Pool({host:'127.0.0.1',port:5432,user:process.env.POSTGRES_USER||'metardu',password:process.env.POSTGRES_PASSWORD,database:process.env.POSTGRES_DB||'metardu'});
const base = process.argv[2] || 'https://metardu.space';
const userId = randomUUID();
const projectId = randomUUID();
const email = `verification-${userId}@example.invalid`;
const password = randomBytes(24).toString('base64url');
let browser;
(async()=>{
  try {
    await pool.query(`INSERT INTO users(id,email,password_hash,full_name,role,email_verified)
      VALUES($1,$2,$3,'Automated verification','surveyor',true)`,[userId,email,await bcrypt.hash(password,10)]);
    await pool.query(`INSERT INTO projects(id,user_id,name,survey_type,boundary_data,utm_zone,hemisphere,datum,surveyor_name,surveyor_license)
      VALUES($1,$2,'Automated workflow verification','cadastral',$3,37,'S','WGS84','TEST FIXTURE - NOT FOR SUBMISSION','TEST-ONLY')`,[projectId,userId,JSON.stringify({startE:500000,startN:9900000})]);
    for(const [i,station] of ['A1','A2','A10','A3'].entries()) {
      await pool.query('INSERT INTO project_fieldbook_entries(project_id,row_index,station,raw_data) VALUES($1,$2,$3,$4)',[projectId,i,station,JSON.stringify({station,bearing:i*90,distance:100})]);
    }
    browser = await chromium.launch({headless:true,channel:'msedge'});
    const context = await browser.newContext();
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto(`${base}/login`,{waitUntil:'networkidle',timeout:60000});
    await page.locator('input[type=email]').fill(email);
    await page.locator('input[type=password]').fill(password);
    await page.getByRole('button',{name:'Sign In',exact:true}).click();
    await page.waitForURL(url=>!url.pathname.startsWith('/login'),{timeout:60000});
    const session = await context.request.get(`${base}/api/auth/session`);
    const auth = await session.json();
    if(!auth.user) throw new Error('Login did not establish a session');
    const results = [{step:'login',status:session.status()}];
    if(process.argv.includes('--login-only')) {
      console.log(JSON.stringify({results,errors},null,2));
      return;
    }
    for(const route of [`/project/${projectId}`,`/project/${projectId}/submission`]) {
      const response = await page.goto(`${base}${route}`,{waitUntil:'domcontentloaded',timeout:60000});
      await page.waitForTimeout(1000);
      results.push({step:route,status:response.status()});
      if(response.status()!==200) throw new Error(`Page failed: ${route}`);
    }
    for(const documentId of ['statutory-workbook','deed-plan','traverse-computation-sheet','area-computation','field-book']) {
      const response = await context.request.post(`${base}/api/submission/generate`,{data:{projectId,documentId},headers:{Origin:base},timeout:120000});
      const result = await response.json();
      if(!response.ok()||!result.fileUrl) throw new Error(`${documentId}: ${JSON.stringify(result)}`);
      const download = await context.request.get(new URL(result.fileUrl,base).href);
      const bytes = (await download.body()).length;
      if(!download.ok()||bytes<100) throw new Error(`${documentId} download failed: ${download.status()}`);
      results.push({step:documentId,status:response.status(),downloadStatus:download.status(),bytes});
    }
    const response = await context.request.post(`${base}/api/submission/package`,{data:{projectId},headers:{Origin:base},timeout:120000});
    const result = await response.json();
    if(!response.ok()||!result.downloadUrl) throw new Error(`Package: ${JSON.stringify(result)}`);
    const download = await context.request.get(new URL(result.downloadUrl,base).href);
    const zip = await download.body();
    if(!download.ok()||zip.toString('ascii',0,2)!=='PK') throw new Error('Package download is not a ZIP');
    results.push({step:'package',status:response.status(),downloadStatus:download.status(),bytes:zip.length});
    const reportId = randomUUID();
    await pool.query(`INSERT INTO survey_reports(id,project_id,user_id,report_title,report_number,input_data,sections)
      VALUES($1,$2,$3,'Saved report verification','TEST-ONLY',$4,$5)`,
      [reportId,projectId,userId,JSON.stringify({clientName:'Test fixture'}),JSON.stringify([
        {section:'RESULTS_AND_ACCURACY',sectionNumber:1,title:'Saved findings',content:'<p>Recorded closure is 1:12345.</p>',autoGenerated:false,completeness:100}
      ])]);
    for(const format of ['pdf','docx']) {
      const reportResponse = await context.request.post(`${base}/api/survey-report/export`,{data:{reportId,format},headers:{Origin:base},timeout:120000});
      const body = await reportResponse.body();
      if(!reportResponse.ok()) throw new Error(`Survey report ${format}: ${body.toString().slice(0,300)}`);
      if(format==='pdf' && body.toString('ascii',0,4)!=='%PDF') throw new Error('Survey report is not a PDF');
      if(format==='docx') {
        const archive = await require('jszip').loadAsync(body);
        const xml = await archive.file('word/document.xml').async('string');
        if(!xml.includes('Recorded closure is 1:12345')) throw new Error('DOCX lost saved content');
      }
      fs.writeFileSync(`live-test-results/verified-saved-report.${format}`,body);
      results.push({step:`saved-report-${format}`,status:reportResponse.status(),bytes:body.length});
    }
    fs.writeFileSync('live-test-results/repair-live-workflow.json',JSON.stringify({results,errors},null,2));
    console.log(JSON.stringify({results,errors},null,2));
    if(errors.length) throw new Error('Browser reported JavaScript errors');
  } finally {
    if(browser) await browser.close();
    await pool.query('DELETE FROM file_uploads WHERE project_id=$1',[projectId]);
    await pool.query('DELETE FROM projects WHERE id=$1 AND user_id=$2',[projectId,userId]);
    await pool.query('DELETE FROM users WHERE id=$1 AND email=$2',[userId,email]);
    await pool.end();
  }
})().catch(error=>{console.error(error.message);process.exitCode=1;});
